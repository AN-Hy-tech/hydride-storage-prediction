"""The published 22 against the set this project now declares, and what the change cost.

Card #25. Selection has been re-run honestly -- inside card #88's folds, on CleanLab-screened
rows (:mod:`hydms.surrogate.selection`) -- and the answer is not the archived 22. This module
turns the tables that run wrote into the comparison the card publishes, and it does so
**without fitting anything**: every number here is read from a CSV a slow-lane run left on
disk, or measured from the curated rows in a second. That is deliberate. A five-fold run at
the configured Boruta budget costs about fifty minutes, so a document regenerated by re-running
selection would be a document nobody regenerates, and a document nobody regenerates is how
``REPORT.md`` came to disagree with the CSVs committed beside it.

**What the comparison is not.** It cannot report a feature the corrected run *added*, because
the candidate pool is the published 22 itself (less
:data:`~hydms.surrogate.select.COSTLY_FEATURE`, card #24's row trade). Widening the pool to
everything the two element tables could offer -- 2,685 names -- is a different piece of work
than hardening Chapter 1, and #24's correction to the "282 candidates" story is why: CBFV's
``magpie`` output, which that number came from, produces none of the published descriptors.
So the old-versus-new relation here is a **subset** relation, and the document says so rather
than printing an empty "added" column and letting a reader draw the wrong conclusion.

**The axis SHAP does not measure.** A feature that cannot be computed for a composition costs
rows, and rows are what a 1,279-row dataset has least of. :func:`row_cost` measures that per
feature over the curated set, so the comparison ranks the old 22 on availability as well as on
importance -- the argument card #19 could only state and card #24 could only settle for one
feature.

The runnable entry point is ``python -m hydms.surrogate.select --emit-comparison``.
"""

